"""Port the labels the stock SEZB1 vendor policy expects from One UI's platform policy.

The stock vendor policy (API 30) refers to Samsung platform types through
versioned attributes (sec_camera_prop_30_0, ...). One UI's system image labels
properties, devices and files with those types; AOSP does not, so on Android 17
vendor HALs see default_prop / device and are denied in enforcing mode. This
regenerates sepolicy/private/samsung_ported.te, property_contexts and the
ported part of file_contexts.

    python3 tools/port_stock_sepolicy.py <one-ui-selinux> <vendor-reference> <a17-sepolicy> <aosp-30-pub.cil>

<one-ui-selinux> holds plat_*/system_ext_* contexts and CIL from the SEZB1
system image; <a17-sepolicy> holds public/ and private/ of system/sepolicy (cnb)
plus lineage/{property,file}_contexts of device/lineage/sepolicy.
"""
import collections
import re
import sys
from pathlib import Path

stock_dir, ref_dir, a17_dir, aosp30 = map(Path, sys.argv[1:5])
device = Path(__file__).resolve().parent.parent
out = device / 'sepolicy/private'

vendor_cil = (ref_dir / 'selinux/vendor_sepolicy.cil').read_text()
vused = collections.Counter(re.findall(r'\b([a-z0-9_]+)_30_0\b', vendor_cil))
aosp30_types = set(re.findall(r'\(typeattribute ([a-z0-9_]+)_30_0\)', aosp30.read_text()))
stock_cil = ''.join(p.read_text() for p in stock_dir.rglob('*_sepolicy.cil'))
mapping = (device / 'patches/sepolicy/0001-restore-api30-compatibility.patch').read_text()
a17_text = ''.join(p.read_text(errors='replace') for p in (a17_dir / 'public').glob('*.te')) + \
    ''.join(p.read_text(errors='replace') for p in (a17_dir / 'private').glob('*.te'))
a17_types = set(re.findall(r'^\s*type\s+([a-z0-9_]+)', a17_text, re.M)) | \
    set(re.findall(r'^\s*(?:system|vendor|product)_[a-z_]*prop\(\s*([a-z0-9_]+)', a17_text, re.M))
a17_attrs = set(re.findall(r'^\s*attribute\s+([a-z0-9_]+)', a17_text, re.M))


def a17_type(t):
    """The Android 17 type an AOSP API 30 type maps to (renamed props)."""
    if t in a17_types:
        return t
    m = re.search(r'\(typeattributeset %s_30_0 \(([^)]*)\)' % t, mapping)
    for candidate in (m.group(1).split() if m else []):
        if candidate in a17_types:
            return candidate
    return None


def contexts(path):
    rows = []
    for line in path.read_text(errors='replace').splitlines():
        line = line.split('#')[0].strip() if not line.lstrip().startswith('/') else line.strip()
        fields = line.split()
        ctx = [f for f in fields if f.startswith('u:object_r:')]
        if line and not line.startswith('#') and ctx:
            rows.append((fields[0], fields[1:fields.index(ctx[0])], ctx[0].split(':')[2],
                         fields[fields.index(ctx[0]) + 1:]))
    return rows


def known(paths):
    return {row[0] for p in paths for row in contexts(p)}


PORTED_MARK = '# --- Generated by tools/port_stock_sepolicy.py below this line ---'
samsung = {}  # type -> kind


def port(t):
    """Return the label to use for stock type t, declaring Samsung types."""
    if not vused[t]:
        return None
    if t in aosp30_types:
        return a17_type(t)
    if t in a17_types:
        return t
    samsung.setdefault(t, None)
    return t


# --- properties ---
stock_props = []
for name in ('plat_property_contexts', 'system_ext_property_contexts', 'product_property_contexts'):
    stock_props += [r for p in stock_dir.rglob(name) for r in contexts(p)]
have = known([a17_dir / 'private/property_contexts', a17_dir / 'lineage/property_contexts',
              ref_dir / 'selinux/vendor_property_contexts'])
a17_props = [r for p in (a17_dir / 'private/property_contexts', a17_dir / 'lineage/property_contexts',
                          ref_dir / 'selinux/vendor_property_contexts') for r in contexts(p)]


def a17_label(name):
    """Label Android 17 + stock vendor give this property today (longest prefix)."""
    best = None
    for n, _, t, extra in a17_props:
        exact = 'exact' in extra
        if (name == n) or (not exact and name.startswith(n)):
            if best is None or len(n) > len(best[0]):
                best = (n, t)
    return best[1] if best else 'default_prop'


props = []
for name, _, t, extra in stock_props:
    if name in have or name.startswith(('vendor.', 'persist.vendor.', 'ro.vendor.', 'ctl.')):
        continue
    # Only fill holes: never take a property away from the label Android 17
    # (or the stock vendor) already gives it.
    if a17_label(name) not in ('default_prop',):
        continue
    label = port(t)
    if label:
        if label in samsung:
            samsung[label] = 'prop'
        props.append(f'{name:56} u:object_r:{label}:s0' + (' ' + ' '.join(extra) if extra else ''))
        have.add(name)

# --- files: devices, sockets and data directories outside system/vendor ---
FILE_PREFIXES = ('/dev/', '/data/log', '/data/sec', '/data/nfc', '/data/misc/elabel', '/data/misc/speg')
have = known([a17_dir / 'private/file_contexts', a17_dir / 'lineage/file_contexts',
              ref_dir / 'selinux/vendor_file_contexts'])
files = []
for p in list(stock_dir.rglob('plat_file_contexts')) + list(stock_dir.rglob('system_ext_file_contexts')):
    for path, kind, t, _ in contexts(p):
        if path in have or not path.startswith(FILE_PREFIXES) or path.startswith('/dev/selinux'):
            continue
        label = port(t)
        if label:
            if label in samsung:
                samsung[label] = 'socket' if path.startswith('/dev/socket/') else 'dev' if path.startswith('/dev/') else 'data'
            files.append(f'{path:40} {" ".join(kind) + " " if kind else ""}u:object_r:{label}:s0')
            have.add(path)

# --- declarations, mirroring One UI's attributes where Android 17 has them ---
stock_attrs = collections.defaultdict(set)
for attr, members in re.findall(r'\(typeattributeset ([a-z0-9_]+) \(([^()]*)\)\)', stock_cil):
    for m in members.split():
        stock_attrs[m].add(attr)
KEEP = set()  # One UI's extra attributes (mlstrustedobject, ...) are not needed here
te = ['# Generated by tools/port_stock_sepolicy.py from the SEZB1 One UI platform policy.',
      '# Samsung platform types the stock vendor policy refers to as <type>_30_0.', '']
for t, kind in sorted(samsung.items()):
    if kind == 'prop':
        te.append(f'system_public_prop({t})')
    else:
        attrs = sorted(a for a in stock_attrs[t] if a in KEEP and a in a17_attrs | KEEP)
        base = {'dev': ['dev_type'], 'socket': ['file_type'], 'data': ['file_type', 'data_file_type', 'core_data_file_type']}[kind]
        te.append(f'type {t}, {", ".join(sorted(set(base) | set(attrs)))};')
    te.append(f'attribute {t}_30_0;')
    te.append(f'typeattribute {t} {t}_30_0;')
(out / 'samsung_ported.te').write_text('\n'.join(te) + '\n')
header = '# Generated by tools/port_stock_sepolicy.py: SEZB1 One UI labels the stock vendor policy uses.\n'
(out / 'property_contexts').write_text(header + '\n'.join(props) + '\n')
manual = (out / 'file_contexts').read_text().split(PORTED_MARK)[0].rstrip('\n')
(out / 'file_contexts').write_text(manual + '\n\n' + PORTED_MARK + '\n' + '\n'.join(files) + '\n')
print(f'{len(props)} property labels, {len(files)} file labels, {len(samsung)} Samsung types')
